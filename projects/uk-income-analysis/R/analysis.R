# Run from the project folder: Rscript R/analysis.R /path/to/input.xlsx
args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 1L) stop('Supply the path to the original Excel workbook.')
if (!requireNamespace('readxl', quietly = TRUE)) stop('Install readxl first.')
d <- as.data.frame(readxl::read_excel(args[[1]]))
x <- c('demox_eiu', 'income_per_person', 'invest_pct_gdp', 'tax_pct_gdp')
required <- c('country', 'year', x, 'gini_index')
if (!all(required %in% names(d))) stop('Missing required columns.')
if (!all(vapply(d[c('year', x, 'gini_index')], is.numeric, logical(1)))) stop('Numeric columns required.')
if (anyNA(d[required]) || anyDuplicated(d$year)) stop('Missing values or duplicate years.')
if (!all(d$country == 'United Kingdom')) stop('Expected UK observations only.')
d <- d[order(d$year), ]
if (nrow(d) <= length(x) + 1L) stop('Insufficient observations.')
out <- file.path('results', 'r-run')
dir.create(out, recursive = TRUE, showWarnings = FALSE)
write.csv(summary(d[c(x, 'gini_index')]), file.path(out, 'summary.csv'))
write.csv(cor(d[c(x, 'gini_index')]), file.path(out, 'correlations.csv'))
model <- lm(gini_index ~ demox_eiu + income_per_person + invest_pct_gdp + tax_pct_gdp, data = d)
write.csv(coef(summary(model)), file.path(out, 'ols_coefficients.csv'))
capture.output(summary(model), file = file.path(out, 'model_summary.txt'))
svg(file.path(out, 'overview.svg'), width = 10, height = 4)
par(mfrow = c(1, 2))
plot(d$year, d$gini_index, type = 'b', col = '#176B87', xlab = 'Year', ylab = 'Gini index', main = 'UK inequality over time')
plot(d$demox_eiu, d$gini_index, col = '#176B87', pch = 19, xlab = 'demox_eiu (supplied scale)', ylab = 'Gini index', main = 'Exploratory association')
invisible(dev.off())
capture.output(sessionInfo(), file = file.path(out, 'sessionInfo.txt'))
message('Outputs written to ', out, '. Interpret this small time-series sample cautiously.')
